// Generates src/i18n/generated/catalogs.js by MERGING two sources:
//
//   1. the backend's own i18n catalogs (internal/i18n/catalogs/*.json) — the
//      source of every `error.*`/`route.*`/... code the Management API returns,
//      so the GUI localises a server code from the server's OWN vocabulary
//      (ADR-0002: the code is the contract, the catalog is translated here);
//   2. the GUI's own label catalogs (src/i18n/gui/*.json) — the `gui.*` keys the
//      shell and pages need, which are not server messages.
//
// The merge is a plain object spread with the GUI labels second: the two key
// namespaces are disjoint (`gui.*` vs the server's prefixes), so no server
// message is ever shadowed by a label.
//
// Run automatically by `npm run prebuild` and therefore by `make web`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const serverDir = join(repo, 'internal', 'i18n', 'catalogs');
const guiDir = join(here, '..', 'src', 'i18n', 'gui');
const outFile = join(here, '..', 'src', 'i18n', 'generated', 'catalogs.js');

const languages = ['en', 'pt-BR'];
const catalogs = {};
for (const lang of languages) {
  const server = JSON.parse(readFileSync(join(serverDir, `${lang}.json`), 'utf8'));
  const gui = JSON.parse(readFileSync(join(guiDir, `${lang}.json`), 'utf8'));
  catalogs[lang] = { ...server, ...gui };
}

const body =
  '// AUTO-GENERATED by scripts/sync-catalogs.mjs. Do not edit by hand.\n' +
  '// Sources: internal/i18n/catalogs/*.json (server codes) +\n' +
  '//          src/i18n/gui/*.json (GUI labels).\n' +
  'export const catalogs = ' +
  JSON.stringify(catalogs, null, 2) +
  ';\n';

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, 'utf8');
console.log(`sync-catalogs: wrote ${outFile}`);
